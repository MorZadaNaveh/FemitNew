def create_article(store_key, cfg, article_data):
    url = f"https://{cfg['store']}/admin/api/2026-01/graphql.json"
    mutation = """
    mutation articleCreate($article: ArticleCreateInput!) {
      articleCreate(article: $article) {
        article { id title handle }
        userErrors { field message }
      }
    }
    """
    resp = requests.post(url, headers={
        "X-Shopify-Access-Token": cfg["token"],
        "Content-Type": "application/json"
    }, json={"query": mutation, "variables": {"article": {
        "blogId": cfg["blog_id"],
        "title": article_data["title"],
        "body": article_data["body"],
        "summary": article_data["excerpt"],
        "isPublished": True,
        "author": {"name": "צוות Femit"},
    }}})
    result = resp.json()
    print(f"[{store_key}] {article_data['key']}:", json.dumps(result, ensure_ascii=False))
    return result

